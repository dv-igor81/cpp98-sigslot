// TDateTime — структура для хранения даты/времени.
// ConversionMode — направление преобразования.
//
// ============================================================================

#ifndef DATETIME_TYPES_H
#define DATETIME_TYPES_H

// ============================================================================
// TDateTime — структура даты/времени
// ============================================================================

typedef struct {
    unsigned char TimeSec;     // Секунды (0-59)
    unsigned char TimeMin;     // Минуты (0-59)
    unsigned char TimeHor;     // Часы (0-23)
    unsigned char TimeWeek;    // День недели (1=Пн, 7=Вс)
    unsigned char TimeDMonth;  // Число месяца (1-31)
    unsigned char TimeMonth;   // Месяц (1-12)
    unsigned char TimeYear;    // Год (00-99, где 00=2000, 99=2099)
} TDateTime;

// ============================================================================
// ConversionMode — направление преобразования
// ============================================================================

enum ConversionMode {
    MODE_EPOCH_TO_DATETIME = 1,   // Unix Time -> Дата/Время
    MODE_DATETIME_TO_EPOCH = 2    // Дата/Время -> Unix Time
};

// ============================================================================
// Константы
// ============================================================================

const int MAX_RESULT_LEN = 512;   // Максимальная длина строки результата
const int SECS_PER_HOUR  = 3600;  // Секунд в часе

#endif // DATETIME_TYPES_H
