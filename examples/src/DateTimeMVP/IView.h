// ============================================================================
// IView.h — Интерфейс вида (абстракция пользовательского интерфейса)
// Borland C++ Builder 6.0 / C++98
// ============================================================================
//
// ЧТО ТАКОЕ VIEW В MVP?
//
//   View (Вид) — это то, что видит пользователь. В нашем случае —
//   консольный ввод и вывод. View НЕ содержит бизнес-логики и НЕ
//   принимает решений. Его единственная задача:
//     1. Показывать информацию пользователю
//     2. Получать ввод от пользователя
//     3. Уведомлять презентер о произошедших событиях (через сигналы)
//
//   View НЕ знает о Model. Он не знает, как выполняется конвертация,
//   не знает о правилах обработки данных.
//
// ПОТОК ВЗАИМОДЕЙСТВИЯ:
//
//   1. showBanner() — показать баннер
//   2. promptTimezone() — запросить часовой пояс -> onTimezoneEntered
//   3. promptMode() — запросить направление -> onModeSelected
//   4. promptEpochInput() или promptDateTimeInput() — запросить данные -> onInputEntered
//   5. showResult() — показать результат
//
// ============================================================================

#ifndef IVIEW_H
#define IVIEW_H

#include "signal_impl.h"
#include "DateTimeTypes.h"

class IView {
public:
    // ========================================================================
    // СИГНАЛЫ: вид излучает их, когда произошло пользовательское событие
    // ========================================================================

    // Пользователь ввёл часовой пояс
    signals::Signal0 onTimezoneEntered;

    // Пользователь выбрал направление преобразования
    signals::Signal0 onModeSelected;

    // Пользователь ввёл значение для преобразования
    signals::Signal0 onInputEntered;

    // ========================================================================
    // ВИРТУАЛЬНЫЕ МЕТОДЫ: презентер вызывает их для управления видом
    // ========================================================================

    // Показать приветственный баннер с информацией о программе
    virtual void showBanner() = 0;

    // Запросить у пользователя часовой пояс
    virtual void promptTimezone() = 0;

    // Запросить у пользователя направление преобразования
    virtual void promptMode() = 0;

    // Запросить у пользователя значение Unix Time
    virtual void promptEpochInput() = 0;

    // Запросить у пользователя дату и время (по полям)
    virtual void promptDateTimeInput() = 0;

    // Показать результат преобразования
    virtual void showResult(const char* text) = 0;

    // Показать сообщение об ошибке
    virtual void showError(const char* message) = 0;

    // ========================================================================
    // ГЕТТЕРЫ: презентер забирает введённые данные
    // ========================================================================

    // Смещение часового пояса в часах (например, +3, -5)
    virtual int getTimezoneOffset() const = 0;

    // Выбранное направление преобразования (1 или 2)
    virtual int getSelectedMode() const = 0;

    // Введённое значение Unix Time
    virtual unsigned int getEpochInput() const = 0;

    // Введённая дата/время
    virtual const TDateTime& getDateTimeInput() const = 0;

    virtual ~IView() {}
};

// Фабричная функция — создаёт конкретную реализацию IView в куче.
// Объявлена здесь, чтобы main.cpp не зависел от ConsoleView.h.
IView* createConsoleView();

#endif // IVIEW_H
