// ============================================================================
// IModel.h — Интерфейс модели (абстракция бизнес-логики)
// Borland C++ Builder 6.0 / C++98
// ============================================================================
//
// ЧТО ТАКОЕ MODEL В MVP?
//
//   Model (Модель) — это «мозг» приложения. Она содержит всю
//   бизнес-логику и данные. В нашем случае модель умеет:
//     • Хранить параметры преобразования (часовой пояс, режим)
//     • Выполнять конвертацию Unix Time <-> TDateTime
//     • Формировать текстовый результат для отображения
//     • Сообщать о результатах через сигналы
//
//   Модель НЕ знает о View. Она не знает, откуда пришли данные
//   (с консоли, из файла, по сети) и куда пойдёт результат.
//
// ============================================================================

#ifndef IMODEL_H
#define IMODEL_H

#include "signal_impl.h"
#include "DateTimeTypes.h"

class IModel {
public:
    // ========================================================================
    // СИГНАЛЫ: модель излучает их при завершении операций
    // ========================================================================

    // Преобразование завершено, результат готов к отображению
    signals::Signal0 onResultReady;

    // Произошла ошибка
    signals::Signal1<const char*> onError;

    // ========================================================================
    // ВИРТУАЛЬНЫЕ МЕТОДЫ: презентер вызывает их для управления моделью
    // ========================================================================

    // Установить смещение часового пояса (в часах, например +3 для Москвы)
    virtual void setTimezoneOffset(int offset_hours) = 0;

    // Установить направление преобразования (1 или 2)
    virtual void setConversionMode(int mode) = 0;

    // Установить входное значение Unix Time
    virtual void setEpochValue(unsigned int epoch) = 0;

    // Установить входное значение даты/времени
    virtual void setDateTime(const TDateTime& dt) = 0;

    // Выполнить преобразование и сформировать результат
    virtual void convert() = 0;

    // ========================================================================
    // ГЕТТЕРЫ: презентер забирает результат
    // ========================================================================

    // Получить сформированную строку результата
    virtual const char* getResult() const = 0;

    virtual ~IModel() {}
};

// Фабричная функция — создаёт конкретную реализацию IModel в куче.
IModel* createDateTimeModel();

#endif // IMODEL_H
