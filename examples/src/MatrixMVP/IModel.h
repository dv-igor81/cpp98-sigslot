// ============================================================================
// IModel.h — Интерфейс модели (абстракция бизнес-логики)
// Borland C++ Builder 6.0 / C++98
// ============================================================================
//
// ЧТО ТАКОЕ MODEL В MVP?
//
//   Model (Модель) — это «мозг» приложения. Она содержит всю
//   бизнес-логику и данные. В нашем случае модель умеет:
//     • Хранить размерности и элементы матриц
//     • Умножать матрицы с проверкой переполнения
//     • Сообщать о результатах и ошибках
//
//   Модель НЕ знает о View. Она не знает, откуда пришли данные
//   (с консоли, из файла, по сети) и куда пойдёт результат.
//   Модель — это «вычислитель»: дал данные -> получил ответ.
//
// ПОЧЕМУ ИНТЕРФЕЙС?
//
//   IModel — абстрактный интерфейс. Конкретная реализация (MatrixModel)
//   скрыта от презентера. Это позволяет:
//     • Заменить реализацию вычислений (например, на GPU)
//     • Создавать mock-объекты для тестирования презентера
//     • Компилировать презентер и вид без знания о матричной алгоритмике
//
// КАК РАБОТАЮТ СИГНАЛЫ МОДЕЛИ?
//
//   Когда модель завершает операцию, она излучает сигнал.
//   Презентер подключён — он получит уведомление и заберёт результат.
//   Модель не знает, кто слушает и что будет сделано с результатом.
//
//   onResultReady     — «Я закончила вычисления, результат готов»
//   onOverflowDetected — «Внимание: произошло переполнение!»
//   onError           — «Произошла ошибка: ...»
//
// ============================================================================

#ifndef IMODEL_H
#define IMODEL_H

#include "signal_impl.h"
#include "MatrixTypes.h"

class IModel {
public:
    // ========================================================================
    // СИГНАЛЫ: модель излучает их при завершении операций
    // ========================================================================

    // Вычисление завершено, результат готов
    signals::Signal0 onResultReady;

    // В процессе вычислений обнаружено переполнение
    signals::Signal0 onOverflowDetected;

    // Произошла ошибка (например, нехватка памяти)
    signals::Signal1<const char*> onError;

    // ========================================================================
    // ВИРТУАЛЬНЫЕ МЕТОДЫ: презентер вызывает их для управления моделью
    // ========================================================================

    // Установить размерности матриц (выделяет память)
    virtual void setDimensions(int rA, int cA, int rB, int cB) = 0;

    // Загрузить данные матрицы A (плоский массив, row-major)
    virtual void loadMatrixA(const type* data, int rows, int cols) = 0;

    // Загрузить данные матрицы B
    virtual void loadMatrixB(const type* data, int rows, int cols) = 0;

    // Выполнить умножение матриц
    virtual void multiply() = 0;

    // ========================================================================
    // ГЕТТЕРЫ: презентер забирает результат
    // ========================================================================

    // Плоский массив результата (rows*cols элементов, row-major)
    virtual const typeres* getResultData() const = 0;
    virtual int getResultRows() const = 0;
    virtual int getResultCols() const = 0;
    virtual bool hasOverflow() const = 0;

    virtual ~IModel() {}
};

// Фабричная функция — создаёт конкретную реализацию IModel в куче.
// Объявлена здесь, чтобы main.cpp не зависел от MatrixModel.h.
IModel* createMatrixModel();

#endif // IMODEL_H
