#ifndef CONSOLE_SETTINGS_KEEPER_H
#define CONSOLE_SETTINGS_KEEPER_H

// ============================================================================
// ПЕРЕЧИСЛЕНИЕ РЕЖИМОВ КОДИРОВКИ ИСХОДНОГО КОДА
// ============================================================================
// Это список возможных форматов текста, в котором написана сама программа.
// Компьютеры по-разному понимают русские буквы, поэтому мы должны сказать
// нашему "переводчику", в каком формате мы даем ему текст.
typedef enum {
    SE_NONE = 0,        // Переводчик выключен, работаем как обычно
    SE_ANSI_1251,       // Старый стандарт Windows (кодировка 1251)
    SE_UTF8_BOM,        // Современный стандарт (UTF-8), но в начале файла есть скрытая метка
    SE_UTF8_NO_BOM      // Современный стандарт (UTF-8) без скрытой метки (мы используем его)
} SourceEncoding;

// ============================================================================
// КЛАСС-ОБЕРТКА ДЛЯ УДОБНОЙ РАБОТЫ
// ============================================================================
// Этот класс нужен для того, чтобы скрыть всю сложную логику перехвата функций
// Windows. Пользователю класса нужно знать только 3 вещи:
// 1. Создать объект (тогда все автоматически настроится)
// 2. Вызвать ApplyRussianSettings (чтобы включить русский)
// 3. Не нужно ничего закрывать вручную - объект сам сделает это при завершении
class ConsoleSettingsKeeper {
public:
    // Конструктор вызывается автоматически при запуске программы.
    // Он делает "подготовку к работе": ищет нужные системные функции Windows.
    ConsoleSettingsKeeper();

    // Деструктор вызывается автоматически, когда программа завершается.
    // Он восстанавливает исходные настройки Windows и ждет нажатия клавиши.
    ~ConsoleSettingsKeeper();

    // Функция, которую мы вызываем из нашей программы, чтобы включить русский язык.
    // encoding - это один из вариантов из перечисления выше (обычно SE_UTF8_NO_BOM).
    void ApplyRussianSettings(SourceEncoding encoding);

    // Функция для программистов. Если русский не работает, она выводит лог того,
    // что именно пошло не так при поиске системных функций.
    void PrintDebug();

private:
    // Внутренний флаг, чтобы деструктор не попытался закрыть консоль дважды
    // (в программировании такие ситуации иногда случаются и их нужно предотвращать).
    static bool m_isDestroyed;
};

// ============================================================================
// ГЛОБАЛЬНЫЙ ОБЪЕКТ
// ============================================================================
// Слово extern означает: "Этот объект где-то существует в программе, просто
// здесь мы о нем предупреждаем, чтобы можно было использовать его в main.cpp".
// Сам объект физически создается в файле console_settings_keeper.cpp
extern ConsoleSettingsKeeper consoleKeeper;

#endif // CONSOLE_SETTINGS_KEEPER_H
