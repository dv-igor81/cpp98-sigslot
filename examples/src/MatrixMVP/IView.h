// ============================================================================
// IView.h — Интерфейс вида (абстракция пользовательского интерфейса)
// Borland C++ Builder 6.0 / C++98
// ============================================================================
//
// ЧТО ТАКОЕ VIEW В MVP?
//
//   View (Вид) — это то, что видит пользователь. В нашем случае —
//   консольный ввод и вывод. View НЕ содержит бизнес-логики и НЕ
//   принимает решений. Его единственная задача:
//     1. Показывать информацию пользователю
//     2. Получать ввод от пользователя
//     3. Уведомлять презентер о произошедших событиях (через сигналы)
//
//   View НЕ знает о Model. Он не знает, как умножаются матрицы,
//   не знает о переполнении, не знает о вычислениях вообще.
//   View — это «глаза и уши» приложения.
//
// ПОЧЕМУ ИНТЕРФЕЙС, А НЕ КОНКРЕТНЫЙ КЛАСС?
//
//   IView — абстрактный интерфейс (все методы чисто виртуальные).
//   Конкретная реализация (ConsoleView) скрыта от презентера.
//   Это позволяет:
//     • Заменить консольный вид на GUI без изменения презентера/модели
//     • Создавать тестовые заглушки (mock-объекты) для модульного тестирования
//     • Компилировать презентер и модель без знания о консоли
//
// КАК РАБОТАЮТ СИГНАЛЫ ВИДА?
//
//   Когда пользователь завершает ввод, вид излучает сигнал.
//   Презентер подключился к этому сигналу — он получит уведомление.
//   Например: пользователь ввёл размерности -> вид излучает
//   onDimensionsEntered -> презентер получает (rA, cA, rB, cB).
//
//   Сигналы — это «радиопередача»: вид не знает, кто слушает.
//   Он просто сообщает: «Произошло такое-то событие».
//
// КАК РАБОТАЮТ ВИРТУАЛЬНЫЕ МЕТОДЫ ВИДА?
//
//   Презентер вызывает виртуальные методы вида, чтобы управлять им:
//   «Покажи баннер», «Запроси размерности», «Покажи результат».
//   Вид решает, КАК именно это сделать (printf, GUI-диалог и т.д.).
//   Презентер решает, КОГДА это сделать.
//
// ============================================================================

#ifndef IVIEW_H
#define IVIEW_H

#include "signal_impl.h"
#include "MatrixTypes.h"

class IView {
public:
    // ========================================================================
    // СИГНАЛЫ: вид излучает их, когда произошло пользовательское событие
    // ========================================================================
    // Презентер подключается к этим сигналам. Вид не знает,
    // кто их получит — он просто «кричит в пустоту».

    // Пользователь ввёл размерности матриц (rA, cA, rB, cB)
    signals::Signal4<int, int, int, int> onDimensionsEntered;

    // Пользователь ввёл все элементы матрицы A
    signals::Signal0 onMatrixAReady;

    // Пользователь ввёл все элементы матрицы B
    signals::Signal0 onMatrixBReady;

    // ========================================================================
    // ВИРТУАЛЬНЫЕ МЕТОДЫ: презентер вызывает их для управления видом
    // ========================================================================
    // Презентер решает КОГДА, вид решает КАК.
    // Никакого printf/cout вне конкретной реализации (ConsoleView)!

    // Показать приветственный баннер с информацией о типах данных
    virtual void showBanner() = 0;

    // Запросить у пользователя размерности матриц
    virtual void promptDimensions() = 0;

    // Запросить у пользователя элементы матрицы A
    virtual void promptMatrixA() = 0;

    // Запросить у пользователя элементы матрицы B
    virtual void promptMatrixB() = 0;

    // Отобразить результат умножения (data — плоский массив, row-major)
    virtual void showResult(const typeres* data, int rows, int cols) = 0;

    // Отобразить сообщение об ошибке (общее, от модели или системы)
    virtual void showError(const char* message) = 0;

    // Отобразить ошибку несовместимых размерностей
    // (cA столбцов матрицы A != rB строк матрицы B)
    virtual void showDimensionMismatch(int cA, int rB) = 0;

    // Отобразить ошибку некорректных размерностей
    // (<=0 или >MAX_DIM)
    virtual void showInvalidDimensions() = 0;

    // Отобразить предупреждение о переполнении
    virtual void showOverflowWarning() = 0;

    // ========================================================================
    // ГЕТТЕРЫ: презентер забирает введённые данные
    // ========================================================================

    virtual int getRowsA() const = 0;
    virtual int getColsA() const = 0;
    virtual int getRowsB() const = 0;
    virtual int getColsB() const = 0;

    // Плоский массив данных матрицы (rows*cols элементов, row-major)
    virtual const type* getMatrixAData() const = 0;
    virtual const type* getMatrixBData() const = 0;

    virtual ~IView() {}
};

// Фабричная функция — создаёт конкретную реализацию IView в куче.
// Объявлена здесь, чтобы main.cpp не зависел от ConsoleView.h.
IView* createConsoleView();

#endif // IVIEW_H
