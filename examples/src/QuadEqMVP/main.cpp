#ifdef __BORLANDC__
#pragma hdrstop
#endif

#include "IView.h"
#include "IModel.h"
#include "Presenter.h"

int main(int argc, char* argv[])
{
    (void)argc;
    (void)argv;

    // Экземпляры создаются в куче через фабричные функции.
    // Мы храним только указатели на базовые интерфейсы.
    IView*  view  = createConsoleView();
    IModel* model = createQuadEqModel();

    // Презентер принимает два указателя на интерфейсы,
    // устанавливает сигнально-слотовые соединения и запускает диалог.
    Presenter presenter(view, model);

    // Освобождение ресурсов
    delete view;
    delete model;

    return 0;
}
