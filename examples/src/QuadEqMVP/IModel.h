//
// ЧТО ТАКОЕ MODEL В MVP?
//
//   Model (Модель) — это «мозг» приложения. Она содержит всю
//   бизнес-логику и данные. В нашем случае модель умеет:
//     • Принимать коэффициенты квадратного уравнения
//     • Решать уравнение (линейное или квадратное)
//     • Сообщать о результатах через сигналы
//
//   Модель НЕ знает о View. Она не знает, откуда пришли данные
//   (с консоли, из файла, по сети) и куда пойдёт результат.
//   Модель — это «вычислитель»: дал данные -> получил ответ.
//
// РЕЗУЛЬТАТ РЕШЕНИЯ:
//
//   Квадратное уравнение ax^2 + bx + c = 0 может дать разные результаты:
//     • LINEAR        — a=0, b!=0: линейное уравнение, один корень
//     • TWO_ROOTS     — D>0: два различных корня
//     • ONE_ROOT      — D=0: один корень (два совпадающих)
//     • NO_REAL_ROOTS — D<0: нет действительных корней
//     • INFINITE      — a=0, b=0, c=0: бесконечно много решений
//     • NO_SOLUTION   — a=0, b=0, c!=0: нет решений
//
//   Модель сохраняет результат решения и предоставляет его через геттеры.
//   Презентер опрашивает модель и решает, какой метод вида вызвать.
//
// ============================================================================

#ifndef IMODEL_H
#define IMODEL_H

#include "signal_impl.h"
#include "QuadEqTypes.h"

// Результат решения уравнения
enum SolveResult {
    SOLVE_LINEAR,         // Линейное уравнение (a=0, b!=0)
    SOLVE_TWO_ROOTS,      // Два различных корня (D>0)
    SOLVE_ONE_ROOT,       // Один корень (D=0)
    SOLVE_NO_REAL_ROOTS,  // Нет действительных корней (D<0)
    SOLVE_INFINITE,       // Бесконечно много решений (0=0)
    SOLVE_NO_SOLUTION     // Нет решений (c!=0)
};

class IModel {
public:
    // ========================================================================
    // СИГНАЛЫ: модель излучает их при завершении операций
    // ========================================================================

    // Решение найдено, результат готов
    signals::Signal0 onResultReady;

    // Произошла ошибка
    signals::Signal1<const char*> onError;

    // ========================================================================
    // ВИРТУАЛЬНЫЕ МЕТОДЫ: презентер вызывает их для управления моделью
    // ========================================================================

    // Установить коэффициенты уравнения
    virtual void setCoefficients(type a, type b, type c) = 0;

    // Решить уравнение
    virtual void solve() = 0;

    // ========================================================================
    // ГЕТТЕРЫ: презентер забирает результат
    // ========================================================================

    // Тип результата решения
    virtual SolveResult getSolveResult() const = 0;

    // Корни (используются для LINEAR, ONE_ROOT, TWO_ROOTS)
    virtual double getRoot1() const = 0;
    virtual double getRoot2() const = 0;

    // Значения проверки: подстановка корня в уравнение
    // (должно быть ~= 0 для правильного корня)
    virtual double getVerification1() const = 0;
    virtual double getVerification2() const = 0;

    virtual ~IModel() {}
};

// Фабричная функция — создаёт конкретную реализацию IModel в куче.
IModel* createQuadEqModel();

#endif // IMODEL_H
