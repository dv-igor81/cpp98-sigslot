// ============================================================================
// IModel.h — Интерфейс модели (абстракция бизнес-логики)
// Borland C++ Builder 6.0 / C++98
// ============================================================================
//
// ЧТО ТАКОЕ MODEL В MVP?
//
//   Model (Модель) — это «мозг» приложения. Она содержит всю
//   бизнес-логику и данные. В нашем случае модель умеет:
//     • Хранить имя и фамилию пользователя
//     • Формировать приветственную строку
//     • Сообщать о результатах через сигналы
//
//   Модель НЕ знает о View. Она не знает, откуда пришли данные
//   (с консоли, из файла, по сети) и куда пойдёт результат.
//   Модель — это «вычислитель»: дал данные -> получил ответ.
//
// ============================================================================

#ifndef IMODEL_H
#define IMODEL_H

#include "signal_impl.h"
#include "GreetingTypes.h"

class IModel {
public:
    // ========================================================================
    // СИГНАЛЫ: модель излучает их при завершении операций
    // ========================================================================

    // Приветствие сформировано и готово к отображению
    signals::Signal0 onGreetingReady;

    // Произошла ошибка
    signals::Signal1<const char*> onError;

    // ========================================================================
    // ВИРТУАЛЬНЫЕ МЕТОДЫ: презентер вызывает их для управления моделью
    // ========================================================================

    // Установить имя пользователя
    virtual void setName(const char* name) = 0;

    // Установить фамилию пользователя (может быть пустой)
    virtual void setSurname(const char* surname) = 0;

    // Сформировать приветствие на основе имени и фамилии
    virtual void buildGreeting() = 0;

    // ========================================================================
    // ГЕТТЕРЫ: презентер забирает результат
    // ========================================================================

    // Получить сформированную приветственную строку
    virtual const char* getGreeting() const = 0;

    virtual ~IModel() {}
};

// Фабричная функция — создаёт конкретную реализацию IModel в куче.
IModel* createGreetingModel();

#endif // IMODEL_H
