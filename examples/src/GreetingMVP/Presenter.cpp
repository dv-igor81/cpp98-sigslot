// ============================================================================
// Presenter.cpp — Реализация презентера
// Borland C++ Builder 6.0 / C++98
// ============================================================================
//
// ПОЛНЫЙ ЖИЗНЕННЫЙ ЦИКЛ ПРИЛОЖЕНИЯ:
//
//   main() создаёт IView* и IModel*, передаёт их в Presenter.
//   Конструктор презентера делает 3 вещи:
//     1. Создаёт слоты и подключает их к сигналам вида и модели
//     2. Показывает баннер (через вид)
//     3. Запрашивает имя (через вид) — это старт потока
//     4. Далее всё работает на сигналах и слотах:
//
//   +-----------------------------------------------------------------+
//   |  View                         Presenter           Model       |
//   |                                                               |
//   |  promptName() --сигнал--> handleNameEntered()                  |
//   |                              +- забирает имя из вида           |
//   |                              +- валидация (не пустое ли?)      |
//   |                              +- model->setName() ------------->|
//   |                              +- promptSurname() -->            |
//   |                                                               |
//   |  promptSurname() --сигнал--> handleSurnameEntered()            |
//   |                              +- забирает фамилию из вида       |
//   |                              +- model->setSurname() ---------->|
//   |                              +- model->buildGreeting() ------->|
//   |                                                               |
//   |                             <--сигнал-- onGreetingReady         |
//   |  showGreeting() <-- handleGreetingReady()                     |
//   |                              +- забирает greeting из модели    |
//   |                                                               |
//   |                             <--сигнал-- onError                 |
//   |  showError() <-- handleModelError()                           |
//   +-----------------------------------------------------------------+
//
//   ПРАВИЛО: Презентер НИКОГДА не общается с консолью напрямую.
//   Весь вывод — только через методы вида.
//   Весь ввод — только через геттеры вида.
//   Все вычисления — только через методы модели.
//
// ============================================================================

#ifdef __BORLANDC__
#pragma hdrstop
#endif

#include "Presenter.h"
#include "GreetingTypes.h"
#include <string.h>

using namespace signals;

// ============================================================================
// Конструктор: установка соединений и запуск потока
// ============================================================================

Presenter::Presenter(IView* view, IModel* model)
    : m_view(view), m_model(model),
      m_slotNameEntered(this, &Presenter::handleNameEntered),
      m_slotSurnameEntered(this, &Presenter::handleSurnameEntered),
      m_slotGreetingReady(this, &Presenter::handleGreetingReady),
      m_slotError(this, &Presenter::handleModelError)
{
    // ---------------------------------------------------------------
    // ШАГ 1: Подключаем слоты презентера к сигналам вида.
    // ---------------------------------------------------------------
    m_view->onNameEntered += m_slotNameEntered;
    m_view->onSurnameEntered += m_slotSurnameEntered;

    // ---------------------------------------------------------------
    // ШАГ 2: Подключаем слоты презентера к сигналам модели.
    // ---------------------------------------------------------------
    m_model->onGreetingReady += m_slotGreetingReady;
    m_model->onError += m_slotError;

    // ---------------------------------------------------------------
    // ШАГ 3: Запускаем поток взаимодействия.
    // ---------------------------------------------------------------
    m_view->showBanner();
    m_view->promptName();
}

Presenter::~Presenter() {}

// ============================================================================
// Обработчики сигналов вида
// ============================================================================

// Пользователь ввёл имя.
// Забираем из вида, проверяем, передаём в модель.
void Presenter::handleNameEntered()
{
    const char* name = m_view->getName();

    // Валидация — это логика презентера.
    // Модель не должна проверять «разумность» имени —
    // это не её дело. Модель — вычислитель, а не валидатор.

    if (name[0] == '\0') {
        m_view->showError("Имя не может быть пустым. Пожалуйста, введите имя.");
        // Повторный запрос имени
        m_view->promptName();
        return;
    }

    // Имя корректно — передаём в модель
    m_model->setName(name);

    // Запрашиваем фамилию (необязательный ввод)
    m_view->promptSurname();
}

// Пользователь ввёл или пропустил фамилию.
// Забираем из вида, передаём в модель, запускаем формирование приветствия.
void Presenter::handleSurnameEntered()
{
    const char* surname = m_view->getSurname();

    // Фамилия может быть пустой — это нормально
    m_model->setSurname(surname);

    // Запускаем формирование приветствия —
    // модель излучит onGreetingReady когда закончит
    m_model->buildGreeting();
}

// ============================================================================
// Обработчики сигналов модели
// ============================================================================

// Модель сформировала приветствие — передаём результат в вид.
void Presenter::handleGreetingReady()
{
    m_view->showGreeting(m_model->getGreeting());
}

// Модель сообщила об ошибке — показываем через вид.
void Presenter::handleModelError(const char* message)
{
    m_view->showError(message);
}
