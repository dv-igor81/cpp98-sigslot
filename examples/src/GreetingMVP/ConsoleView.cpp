// ============================================================================
// ConsoleView.cpp — Консольная реализация IView
// Borland C++ Builder 6.0 / C++98
// ============================================================================
//
// ЕДИНСТВЕННЫЙ модуль, работающий с консолью.
// Ни презентер, ни модель, ни main() не содержат ни одного printf/scanf.
// Все пользовательские сообщения и весь ввод — только здесь.
//
// ПРИНЦИП РАБОТЫ:
//
//   1. Презентер вызывает promptName() -> мы спрашиваем пользователя
//      через консоль (scanf), сохраняем ответ и излучаем onNameEntered.
//
//   2. Презентер вызывает promptSurname() -> мы спрашиваем фамилию
//      через fgets (необязательный ввод, Enter = пропустить),
//      сохраняем ответ и излучаем onSurnameEntered.
//
//   3. Презентер вызывает showGreeting() -> мы выводим приветствие.
//
//   Геттеры (getName, getSurname) позволяют презентеру забрать
//   введённые данные и передать их в модель.
//
// ДВА СПОСОБА ВВОДА:
//
//   Имя — scanf(" %99[^\n]", name):
//     • Пробел перед %99[^\n] «съедает» \n от предыдущего ввода
//     • Читает до перевода строки, но не включая его
//     • Возвращает 1 при успехе
//
//   Фамилия — fgets(name, sizeof(name), stdin):
//     • Захватывает символ \n (нажатие Enter)
//     • Нужно вручную обрезать \n через strcspn
//     • Если сразу нажать Enter — строка = "\n" -> фамилия = ""
//
// ============================================================================

#ifdef __BORLANDC__
#pragma hdrstop
#endif

// ============================================================================
// ПОДКЛЮЧЕНИЕ БИБЛИОТЕК
// ============================================================================
#include <stdio.h>     /* printf, scanf, fgets */
#include <string.h>    /* strncpy, strcspn */

#include "ConsoleView.h"
#include "GreetingTypes.h"

#include "console_settings_keeper.h"

// ============================================================================
// ConsoleView — реализация
// ============================================================================

ConsoleView::ConsoleView()
{
    m_name[0] = '\0';
    m_surname[0] = '\0';

    // Применяем настройки консоли для корректного отображения русских букв
    consoleKeeper.ApplyRussianSettings(SE_ANSI_1251);
}

ConsoleView::~ConsoleView() {}

// --- Баннер: показывается при запуске приложения ---

void ConsoleView::showBanner()
{
    printf("============================================================\n");
    printf("  ПРИВЕТСТВИЕ ПОЛЬЗОВАТЕЛЯ — Паттерн MVP + Сигналы/Слоты\n");
    printf("  Демонстрация двух способов ввода: scanf и fgets\n");
    printf("============================================================\n\n");
}

// --- Ввод имени (способ 1: scanf) ---

void ConsoleView::promptName()
{
    printf("Введите ваше имя: ");

    // scanf с форматом %[^\n] читает все символы до перевода строки,
    // но НЕ считывает сам символ \n. Он остаётся в буфере stdin!
    // Пробел перед %99[^\n] «съедает» \n от предыдущего ввода, но
    // после scanf наш \n всё равно останется в буфере.
    // Поэтому после scanf нужно «добить» \n из буфера — иначе
    // следующий fgets прочитает пустую строку вместо фамилии.
    if (scanf(" %99[^\n]", m_name) == 1)
    {
        // Имя успешно считано — очищаем \n из буфера
        int c;
        while ((c = getchar()) != '\n' && c != EOF) {}
        // Уведомляем презентер
        onNameEntered.emit_();
    }
    else
    {
        // Ошибка ввода — сбрасываем имя и всё равно уведомляем,
        // чтобы презентер мог обработать пустое имя
        m_name[0] = '\0';
        // Также очищаем буфер
        int c;
        while ((c = getchar()) != '\n' && c != EOF) {}
        onNameEntered.emit_();
    }
}

// --- Ввод фамилии (способ 2: fgets, необязательный) ---

void ConsoleView::promptSurname()
{
    printf("Введите вашу фамилию (или нажмите Enter, чтобы пропустить): ");

    // fgets захватывает символ нажатия Enter (\n).
    // Если пользователь сразу нажал Enter, в буфере будет "\n".
    if (fgets(m_surname, sizeof(m_surname), stdin) != NULL)
    {
        // Находим символ \n и заменяем его на нулевой terminator (\0),
        // чтобы он не выводился лишней пустой строкой.
        int pos = strcspn(m_surname, "\n");
        m_surname[pos] = '\0';

        // Если пользователь сразу нажал Enter — фамилия пустая,
        // что означает отказ от ввода фамилии (это допустимо).
    }
    else
    {
        // Ошибка чтения — сбрасываем фамилию
        m_surname[0] = '\0';
    }

    // Уведомляем презентер: ввод фамилии завершён (может быть пустой)
    onSurnameEntered.emit_();
}

// --- Вывод приветствия ---

void ConsoleView::showGreeting(const char* greeting)
{
    printf("\n============================================================\n");
    printf("  %s\n", greeting);
    printf("============================================================\n\n");
}

// --- Вывод ошибки ---

void ConsoleView::showError(const char* message)
{
    printf("\nОшибка: %s\n", message);
}

// --- Геттеры: презентер забирает введённые данные ---

const char* ConsoleView::getName() const { return m_name; }
const char* ConsoleView::getSurname() const { return m_surname; }


