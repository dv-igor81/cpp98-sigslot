//
// ПОРЯДОК ДЕЙСТВИЙ:
//   1. Создаём вид (ConsoleView) в куче, храним как IView*
//   2. Создаём модель (GreetingModel) в куче, храним как IModel*
//   3. Создаём презентер, передавая ему оба указателя
//   4. Презентер в конструкторе подключает сигналы к слотам,
//      показывает баннер и запускает диалог с пользователем
//   5. По завершении — освобождаем ресурсы
//
// ============================================================================

#ifdef __BORLANDC__
#pragma hdrstop
#endif

#include "IView.h"
#include "IModel.h"
#include "Presenter.h"

int main(int argc, char* argv[])
{
    (void)argc;
    (void)argv;

    // Экземпляры создаются в куче через фабричные функции.
    // Мы храним только указатели на базовые интерфейсы —
    // конкретные классы (ConsoleView, GreetingModel) нам неизвестны.
    IView*  view  = createConsoleView();
    IModel* model = createGreetingModel();

    // Презентер принимает только два указателя на интерфейсы.
    // В конструкторе устанавливаются сигнально-слотовые соединения
    // и запускается весь поток взаимодействия.
    Presenter presenter(view, model);

    // Освобождение ресурсов
    delete view;
    delete model;

    return 0;
}
