// ============================================================================
// IPresenter.h -- Базовый интерфейс презентера
// Borland C++ Builder 6.0 / C++98
// ============================================================================
//
// Каждый экран имеет свой собственный презентер.
// Initialize() -- подписка на сигналы вида (аналог += в C#)
// Destroy()    -- отписка от сигналов вида (аналог -= в C#)
//
// ВАЖНО: Destroy() должен вызываться ПЕРЕД удалением презентера,
//        чтобы разорвать двусторонние связи View<->Presenter
//        и предотвратить утечки памяти.
//
// ============================================================================

#ifndef IPRESENTER_H
#define IPRESENTER_H

class IPresenter {
public:
    virtual ~IPresenter() {}

    // Подписка на сигналы вида и отображение начальных данных
    virtual void initialize() = 0;

    // Отписка от сигналов вида (предотвращение утечек памяти)
    virtual void destroy() = 0;
};

#endif // IPRESENTER_H
