//
// Структура SharedData — данные, которые разделяются между тремя формами
// через модель. Содержит текстовую строку и числовой счётчик.
//
// ПРИНЦИП MVP: Представление (View) не знает, откуда берутся данные.
// Модель (Model) не знает, как данные отображаются.
// Презентер (Presenter) связывает их.
//
// ============================================================================

#ifndef NAVIGATOR_TYPES_H
#define NAVIGATOR_TYPES_H

const int MAX_TEXT_LEN = 256;

// SharedData — «посылка», которую модель передаёт видам через презентер.
// Фиксированный буфер вместо std::string — совместимость с BCB6 VCL.
struct SharedData {
    char text[MAX_TEXT_LEN];  // Текстовая строка
    int  count;               // Числовой счётчик

    SharedData();             // Конструктор: text="", count=1
    void clear();             // Сброс к начальным значениям
};

#endif // NAVIGATOR_TYPES_H
