// Структура SharedData -- данные, которые разделяются между формами
// через модель. Содержит текстовую строку и числовой счётчик.
//
// Header-only: реализация inline для исключения .cpp-файла.
//
// ============================================================================

#ifndef SHAREDDATA_H
#define SHAREDDATA_H

const int MAX_TEXT_LEN = 256;

// SharedData -- «посылка», которую модель передаёт видам через презентер.
// Фиксированный буфер вместо std::string -- совместимость с BCB6 VCL.
struct SharedData {
    char text[MAX_TEXT_LEN];  // Текстовая строка
    int  count;               // Числовой счётчик
    bool isFirst;

    SharedData() : count(1), isFirst(false)
    {
        text[0] = '\0';
    }

    void clear()
    {
        text[0] = '\0';
        count = 1;
    }
};

#endif // SHAREDDATA_H
